import pool from "../db.js"

export const getCategories = async (req, res) => {
    try {
        const result = await pool.query('SELECT * FROM categories ORDER BY name ASC')
        // console.log(result);
        res.json(result.rows);
    } catch (error) {
        console.error('Error fetching categories:', err.message);
        res.status(500).json({ error: 'Server error' });
    }
}

export const getProducts = async (req, res) => {
    try {
        const query = `
            SELECT p.*, c.name as category_name 
            FROM products p
            LEFT JOIN categories c ON p.category_id = c.id
            ORDER BY p.created_at DESC
        `;
        const result = await pool.query(query);
        res.json(result.rows);
    } catch (err) {
        console.error('Error fetching products:', err.message);
        res.status(500).json({ error: 'Server error' });
    }
};

export const getProductById = async (req, res) => {
    const productId = req.params.id;

    try {
        const productResult = await pool.query(
            `SELECT p.*, c.name as category_name 
             FROM products p
             LEFT JOIN categories c ON p.category_id = c.id
             WHERE p.id = $1`,
            [productId]
        );

        if (productResult.rows.length === 0) {
            return res.status(404).json({ error: 'Product not found' });
        }

        const product = productResult.rows[0];

        const variantsResult = await pool.query(
            'SELECT * FROM product_variants WHERE product_id = $1 ORDER BY size, color',
            [productId]
        );

        product.variants = variantsResult.rows;

        res.json(product);
        // console.log(product);
    } catch (err) {
        console.error('Error fetching product by ID:', err.message);
        res.status(500).json({ error: 'Server error' });
    }
};

export const createProduct = async (req, res) => {
    const { category_name, name, description, base_price, variants } = req.body;
    const client = await pool.connect();

    try {
        await client.query('BEGIN');

        const categoryResult = await client.query("SELECT id FROM categories WHERE name= $1", [category_name])

        let category_id;

        if (categoryResult.rows.length === 0) {
            const newCategoryResult = await client.query(
                'INSERT INTO categories (name, description) VALUES ($1, $2) RETURNING id',
                [category_name, `Autogenerated category for ${category_name}`]
            );
            category_id = newCategoryResult.rows[0].id;
        } else {
            category_id = categoryResult.rows[0].id;
        }


        const productQuery = `
            INSERT INTO products (category_id, name, description, base_price) 
            VALUES ($1, $2, $3, $4) 
            RETURNING *
        `;
        const productResult = await client.query(productQuery, [category_id, name, description, base_price]);
        const newProduct = productResult.rows[0];

        if (variants && variants.length > 0) {
            const variantQuery = `
                INSERT INTO product_variants (product_id, sku, size, color, stock_quantity, price_override)
                VALUES ($1, $2, $3, $4, $5, $6)
                RETURNING *
            `;

            const insertedVariants = [];
            for (const variant of variants) {
                const variantResult = await client.query(variantQuery, [
                    newProduct.id,
                    variant.sku,
                    variant.size,
                    variant.color,
                    variant.stock_quantity,
                    variant.price_override || null
                ]);
                insertedVariants.push(variantResult.rows[0]);
            }

            newProduct.variants = insertedVariants;
        }
        await client.query('COMMIT');

        res.status(201).json({
            message: 'Product created successfully',
            product: newProduct
        });

    } catch (err) {
        await client.query('ROLLBACK');
        console.error('Error creating product:', err.message);
        res.status(500).json({ error: 'Server error during product creation' });
    } finally {
        client.release();
    }

}