/**
 * Validate 10-digit Indian mobile number
 * Accepts formats like: 9876543210, +91 9876543210, +91-9876543210, 09876543210
 * Returns clean 10-digit string if valid, or null if invalid
 */
export const cleanAndValidateIndianMobile = (phone) => {
  if (!phone) return null;
  const digitsOnly = String(phone).replace(/\D/g, '');
  
  let tenDigit = null;
  if (digitsOnly.length === 10) {
    tenDigit = digitsOnly;
  } else if (digitsOnly.length === 11 && digitsOnly.startsWith('0')) {
    tenDigit = digitsOnly.slice(1);
  } else if (digitsOnly.length === 12 && digitsOnly.startsWith('91')) {
    tenDigit = digitsOnly.slice(2);
  }

  if (tenDigit && /^[6-9]\d{9}$/.test(tenDigit)) {
    return tenDigit;
  }
  return null;
};

/**
 * Validate 6-digit Indian Postal PIN Code
 * First digit must be 1-9 (cannot start with 0)
 */
export const validateIndianPincode = (pincode) => {
  if (!pincode) return false;
  const cleaned = String(pincode).trim();
  return /^[1-9][0-9]{5}$/.test(cleaned);
};
